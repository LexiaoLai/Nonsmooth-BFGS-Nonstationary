#!/usr/bin/env python3
"""Execute the existing notebook and check its saved mathematical outputs.

Use --write after editing the notebook to refresh its executed outputs.
No notebook cells or mathematical definitions are generated by this script.
"""
import argparse
import ast
import copy
import json
from pathlib import Path
import sys
import tempfile

import nbformat
from nbclient import NotebookClient
from jupyter_client import KernelManager
from jupyter_client.kernelspec import KernelSpecManager

NOTEBOOK = Path(__file__).with_name("verification.ipynb")


def validate_sources(notebook):
    """Keep the notebook's imports self-contained; reject explicit file I/O."""
    allowed = {"fractions", "platform", "sympy", "IPython.display"}
    for cell in notebook.cells:
        if cell.cell_type != "code":
            continue
        for node in ast.walk(ast.parse(cell.source)):
            imports = ([alias.name for alias in node.names] if isinstance(node, ast.Import)
                       else [node.module] if isinstance(node, ast.ImportFrom) else [])
            if any(name not in allowed for name in imports):
                raise ValueError("Notebook imports must use only its declared packages")
            if isinstance(node, ast.Call):
                function = node.func
                if (isinstance(function, ast.Name) and function.id in
                        {"open", "exec", "eval", "compile", "__import__"}) or (
                        isinstance(function, ast.Attribute) and function.attr in
                        {"open", "read", "read_text", "read_bytes", "write_text", "write_bytes"}):
                    raise ValueError("Notebook must not read or write companion files")


def math_outputs(notebook):
    return [[output.data["text/latex"] for output in cell.outputs
             if "text/latex" in output.get("data", {})]
            for cell in notebook.cells if cell.cell_type == "code"]


def check_saved_outputs(saved, executed):
    """Compare computed mathematics, ignoring timings and version strings."""
    cells = [cell for cell in saved.cells if cell.cell_type == "code"]
    if [cell.execution_count for cell in cells] != list(range(1, len(cells) + 1)):
        raise ValueError("Saved notebook is not fully executed; run with --write")
    if any(output.output_type == "error" for cell in cells for output in cell.outputs):
        raise ValueError("Saved notebook contains an error")
    fresh = math_outputs(executed)
    if not any(fresh) or math_outputs(saved) != fresh:
        raise ValueError("Saved mathematical outputs are stale; run with --write")


def execute(notebook):
    validate_sources(notebook)
    fresh = copy.deepcopy(notebook)
    for cell in fresh.cells:
        if cell.cell_type == "code":
            cell.outputs, cell.execution_count = [], None
            cell.metadata.pop("execution", None)
    with tempfile.TemporaryDirectory(prefix="bfgs-notebook-") as folder:
        base = Path(folder)
        spec, working = base / "bfgs-verification", base / "empty"
        spec.mkdir()
        working.mkdir()
        (spec / "kernel.json").write_text(json.dumps({
            "argv": [sys.executable, "-m", "ipykernel_launcher", "-f", "{connection_file}"],
            "display_name": "BFGS verification", "language": "python"}))
        manager = KernelManager(kernel_name="bfgs-verification",
                                kernel_spec_manager=KernelSpecManager(kernel_dirs=[folder]))
        try:
            NotebookClient(fresh, km=manager, timeout=300, allow_errors=False).execute(cwd=str(working))
        finally:
            if manager.has_kernel:
                manager.shutdown_kernel(now=True)
        if list(working.iterdir()):
            raise ValueError("Notebook wrote files in its empty working directory")
    nbformat.validate(fresh)
    return fresh


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="refresh the notebook's executed outputs")
    args = parser.parse_args()
    saved = nbformat.read(NOTEBOOK, as_version=4)
    fresh = execute(saved)
    if args.write:
        check_saved_outputs(fresh, fresh)
        for cell in fresh.cells:
            cell.metadata.pop("execution", None)
        nbformat.write(fresh, NOTEBOOK)
    else:
        check_saved_outputs(saved, fresh)
    outputs = math_outputs(fresh)
    print(f"PASS: {len(outputs)} code cells executed in a fresh kernel and empty directory; "
          f"{sum(map(len, outputs))} mathematical outputs {'refreshed' if args.write else 'match the saved notebook'}.")


if __name__ == "__main__":
    main()
